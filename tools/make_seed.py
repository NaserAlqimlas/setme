"""Turn vb_skill.md into SQL seed files for Supabase.

Usage:
  python3 tools/make_seed.py path/to/vb_skill.md --rater "Nasser=you@example.com" --rater "Reem=reem@example.com"

Writes to private/ (git-ignored, since it contains ratings):
  seed.sql          players (gender, setting role, playing)
  seed_ratings.sql  each rating table, attached to that rater's account (run after they've signed in once)
  fixture.json      the same data for tests/test_teams.mjs
"""
import argparse, json, os, re

SKILLS = ['receiving', 'hitting', 'hustle', 'serve', 'blocking']

ap = argparse.ArgumentParser()
ap.add_argument('doc')
ap.add_argument('--rater', action='append', default=[], help='TableOwner=email, e.g. Nasser=me@x.com')
args = ap.parse_args()
emails = dict(r.split('=', 1) for r in args.rater)

txt = open(args.doc, encoding='utf-8').read().replace('⁠', '')
lines = txt.split('\n')

def section(name):
    m = re.search(r'^## ' + name + r'\s*$(.*?)(?=^#+ |\Z)', txt, re.M | re.S | re.I)
    return m.group(1) if m else ''

def num(v):
    v = v.strip().upper()
    return None if v in ('', 'U') else float(v)

tables = {}  # owner -> {name: row}
for i, l in enumerate(lines):
    if not l.startswith('|name|'):
        continue
    owner = next(re.search(r'\((.+?)\)', lines[j]).group(1) for j in range(i, -1, -1) if lines[j].startswith('# ') and '(' in lines[j])
    cols = [c.strip() for c in l.strip('|').split('|')]
    rows = {}
    for row in lines[i + 2:]:
        if not row.strip() or row.startswith('#'):
            break
        cells = [c.strip() for c in row.split('|')]
        d = dict(zip(cols, cells))
        rows[d['name']] = d
    tables[owner] = rows

master = next(iter(tables.values()))  # first table holds gender and setting roles
playing = {m.strip() for m in re.findall(r'^- (.+)$', section('Playing'), re.M)}
combos = [[x.strip() for x in m.split(',')] for m in re.findall(r'^- (.+)$', section('Combos'), re.M) if ',' in m]

q = lambda s: "'" + s.replace("'", "''") + "'"
sqlnum = lambda v: 'null' if v is None else f'{v:g}'

os.makedirs('private', exist_ok=True)
with open('private/seed.sql', 'w', encoding='utf-8') as f:
    f.write('-- Generated by tools/make_seed.py\n')
    f.write('insert into players (name, gender, setting, playing) values\n')
    vals = []
    for name, d in master.items():
        g = d.get('gender', 'U').upper() if d.get('gender', 'U').upper() in ('M', 'F') else 'U'
        s = d.get('setting', 'N').upper() if d.get('setting', 'N').upper() in ('M', 'B') else 'N'
        vals.append(f'  ({q(name)}, {q(g)}, {q(s)}, {str(name in playing).lower()})')
    f.write(',\n'.join(vals) + '\non conflict (name) do update set gender = excluded.gender, setting = excluded.setting, playing = excluded.playing;\n\n')

with open('private/seed_ratings.sql', 'w', encoding='utf-8') as f:
    f.write('-- Generated by tools/make_seed.py. Each rater must have an account first.\n')
    for owner, rows in tables.items():
        email = emails.get(owner)
        if not email:
            print(f'skipping ratings for {owner}: no --rater {owner}=email given')
            continue
        f.write(f'\n-- {owner}\n')
        for name, d in rows.items():
            v = ', '.join(sqlnum(num(d.get(s, ''))) for s in SKILLS)
            f.write(f'insert into ratings (rater_id, player_id, {", ".join(SKILLS)}) '
                    f'select u.id, p.id, {v} from auth.users u, players p where u.email = {q(email)} and p.name = {q(name)} '
                    f'on conflict (rater_id, player_id) do update set ' + ', '.join(f'{s} = excluded.{s}' for s in SKILLS) + ';\n')

with open('private/fixture.json', 'w', encoding='utf-8') as f:
    json.dump({
        'players': [{'id': n, 'name': n, 'gender': d.get('gender', 'U'), 'setting': d.get('setting', 'N') if d.get('setting') in ('M', 'B') else 'N', 'playing': n in playing} for n, d in master.items()],
        'ratings': [{'rater_id': owner, 'player_id': n, **{s: num(d.get(s, '')) for s in SKILLS}} for owner, rows in tables.items() for n, d in rows.items()],
        'combos': combos,
    }, f, indent=1)

print(f'{len(master)} players, {len(playing)} playing, {len(combos)} combos, rating tables: {", ".join(tables)}')
